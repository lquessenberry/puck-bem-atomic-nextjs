export function TeamMemberCard({
  avatarSrc,
  name,
  role,
  bio,
  socials = [],
  variant = "default",
  newTab = true,
}: TeamMemberCardProps) {
  return (
    <article
      className={[
        styles.teamMemberCard,
        styles[`teamMemberCard--variant-${variant}`],
      ].join(" ")}
    >
      <div className={styles.teamMemberCard__avatar}>
        <Image
          src={avatarSrc}
          alt={name}
          width={120}
          height={120}
          className={styles.teamMemberCard__image}
        />
      </div>
      <div className={styles.teamMemberCard__content}>
        <h3 className={styles.teamMemberCard__name}>{name}</h3>
        <span className={styles.teamMemberCard__role}>{role}</span>
        <p className={styles.teamMemberCard__bio}>{bio}</p>
        {socials.length > 0 && (
          <div className={styles.teamMemberCard__socials}>
            {socials.map((social) => (
              <a
                key={social.platform}
                href={social.href}
                className={styles.teamMemberCard__socialLink}
                aria-label={social.platform}
                {...(newTab && {
                  target: "_blank",
                  rel: "noopener noreferrer",
                })}
              >
                {socialIcons[social.platform]}
              </a>
            ))}
          </div>
        )}
      </div>
    </article>
  );
}

